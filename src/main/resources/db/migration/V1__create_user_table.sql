create table client
(
    id           bigint generated by default as identity
        primary key,
    country_code varchar(255),
    phone_number varchar(255),
    street       varchar(255),
    city         varchar(255),
    state        varchar(255),
    postal_code  varchar(255),
    email        varchar(255),
    name         varchar(255),
    surname      varchar(255)
);

alter table client
    owner to user_svc;

